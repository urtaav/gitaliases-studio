import type { Alias } from './types';

/** Always quotes, so any character survives git's config parser unchanged. */
export function quoteConfigValue(value: string): string {
  const escaped = value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t');
  return `"${escaped}"`;
}

/** A description becomes a "#:" comment line, read back by git cheat; git ignores it. */
const descriptionLine = (d: string) => `\t#: ${d.replace(/[\r\n]+/g, ' ').trim()}`;

export function serializeAliasFile(
  aliases: (Pick<Alias, 'name' | 'value'> & { description?: string })[],
  generatedAt: Date = new Date(),
): string {
  const date = generatedAt.toISOString().slice(0, 10);
  const lines = [
    `# Git aliases generated by GitAliases Studio on ${date}.`,
    '# Connect it with: git config --global --replace-all include.path ~/.gitaliases gitaliases',
    '[alias]',
    ...[...aliases]
      .sort((a, b) => a.name.localeCompare(b.name))
      .flatMap((a) => [
        ...(a.description ? [descriptionLine(a.description)] : []),
        `\t${a.name} = ${quoteConfigValue(a.value)}`,
      ]),
  ];
  return lines.join('\n') + '\n';
}
